-- Long-term goals for kids, and manual point changes with a written reason.
-- Apply after family_access.sql and family_chore_due_dates.sql.
--
-- A child's balance becomes: approved chore points + point adjustments
-- (goal bonuses, parent add/subtract) - redeemed prize points. Every change is
-- its own row, so a balance can always be explained and nothing is rewritten.
begin;

create table if not exists public.goals (
  id bigint generated by default as identity primary key,
  created_at timestamptz not null default now(),
  family_code text not null,
  kid_id uuid not null references public.profiles (id) on delete cascade,
  title text not null,
  details text,
  bonus_points integer not null default 0,
  status text not null default 'active',
  completed_at timestamptz,
  completed_by uuid references public.profiles (id) on delete set null,
  achieved_at timestamptz,
  awarded_points integer not null default 0,
  created_by uuid references public.profiles (id) on delete set null,
  constraint goals_title_length check (pg_catalog.char_length(pg_catalog.btrim(title)) between 1 and 120),
  constraint goals_details_length check (details is null or pg_catalog.char_length(details) <= 500),
  constraint goals_bonus_range check (bonus_points >= 0 and bonus_points <= 10000),
  constraint goals_awarded_range check (awarded_points >= 0 and awarded_points <= 10000),
  constraint goals_status_check check (status in ('active', 'pending', 'achieved', 'archived'))
);

-- A child marks their goal done ('pending') and a parent confirms it. These
-- also exist on a table created by an earlier run of this file.
alter table public.goals add column if not exists completed_at timestamptz;
alter table public.goals add column if not exists completed_by uuid references public.profiles (id) on delete set null;
alter table public.goals drop constraint if exists goals_status_check;
alter table public.goals add constraint goals_status_check check (status in ('active', 'pending', 'achieved', 'archived'));

create table if not exists public.point_adjustments (
  id bigint generated by default as identity primary key,
  created_at timestamptz not null default now(),
  family_code text not null,
  kid_id uuid not null references public.profiles (id) on delete cascade,
  parent_id uuid references public.profiles (id) on delete set null,
  parent_name text not null,
  amount integer not null,
  note text not null,
  goal_id bigint references public.goals (id) on delete set null,
  constraint point_adjustments_amount_range check (amount <> 0 and pg_catalog.abs(amount) <= 10000),
  constraint point_adjustments_note_length check (pg_catalog.char_length(pg_catalog.btrim(note)) between 1 and 200)
);

alter table public.goals enable row level security;
alter table public.point_adjustments enable row level security;

revoke all on public.goals, public.point_adjustments from public, anon;
grant select, insert, update on public.goals to authenticated;
grant select, insert on public.point_adjustments to authenticated;
revoke delete on public.goals, public.point_adjustments from authenticated;
revoke update on public.point_adjustments from authenticated;
grant usage, select on all sequences in schema public to authenticated;

drop policy if exists ct_goals_read on public.goals;
create policy ct_goals_read on public.goals for select to authenticated using (
  family_code = (select choretracker_private.current_family())
  and ((select choretracker_private.current_role()) = 'parent' or kid_id = (select auth.uid()))
);
drop policy if exists ct_goals_insert on public.goals;
create policy ct_goals_insert on public.goals for insert to authenticated with check (
  family_code = (select choretracker_private.current_family())
  and (select choretracker_private.current_role()) = 'parent'
  and exists (select 1 from public.profiles p
    where p.id = kid_id and p.family_code = goals.family_code and p.role = 'kid')
);
drop policy if exists ct_goals_update on public.goals;
create policy ct_goals_update on public.goals for update to authenticated using (
  family_code = (select choretracker_private.current_family())
  and (select choretracker_private.current_role()) = 'parent'
) with check (
  family_code = (select choretracker_private.current_family())
  and (select choretracker_private.current_role()) = 'parent'
  and exists (select 1 from public.profiles p
    where p.id = kid_id and p.family_code = goals.family_code and p.role = 'kid')
);

-- A child may mark their own goal done and take that back. The trigger below
-- is what stops them from awarding the bonus themselves.
drop policy if exists ct_goals_kid_update on public.goals;
create policy ct_goals_kid_update on public.goals for update to authenticated using (
  family_code = (select choretracker_private.current_family())
  and (select choretracker_private.current_role()) = 'kid'
  and kid_id = (select auth.uid())
) with check (
  family_code = (select choretracker_private.current_family())
  and (select choretracker_private.current_role()) = 'kid'
  and kid_id = (select auth.uid())
);

drop policy if exists ct_adjustments_read on public.point_adjustments;
create policy ct_adjustments_read on public.point_adjustments for select to authenticated using (
  family_code = (select choretracker_private.current_family())
  and ((select choretracker_private.current_role()) = 'parent' or kid_id = (select auth.uid()))
);
drop policy if exists ct_adjustments_insert on public.point_adjustments;
create policy ct_adjustments_insert on public.point_adjustments for insert to authenticated with check (
  family_code = (select choretracker_private.current_family())
  and (select choretracker_private.current_role()) = 'parent'
  and kid_id <> (select auth.uid())
  and exists (select 1 from public.profiles p
    where p.id = kid_id and p.family_code = point_adjustments.family_code and p.role = 'kid')
);

-- A goal belongs to one child in the caller's family. A child can only mark
-- their own goal done ('pending'); a parent turns that into 'achieved' and the
-- bonus trigger below pays the points once.
create or replace function choretracker_private.prepare_goal_change()
returns trigger language plpgsql security definer set search_path = '' as $$
declare caller_role text;
begin
  select p.role into caller_role from public.profiles p where p.id = auth.uid();
  if caller_role is null then
    raise exception 'A family profile is required' using errcode = '42501';
  end if;

  new.title := pg_catalog.btrim(new.title);
  if new.title is null or new.title = '' then
    raise exception 'Give the goal a name';
  end if;
  new.details := nullif(pg_catalog.btrim(coalesce(new.details, '')), '');

  if not exists (select 1 from public.profiles p
      where p.id = new.kid_id and p.family_code = new.family_code and p.role = 'kid') then
    raise exception 'Choose a child in your family for this goal' using errcode = '42501';
  end if;

  if tg_op = 'INSERT' then
    if caller_role is distinct from 'parent' then
      raise exception 'Only a parent can add a goal' using errcode = '42501';
    end if;
    new.status := 'active';
    new.awarded_points := 0;
    new.achieved_at := null;
    new.completed_at := null;
    new.completed_by := null;
    new.created_by := coalesce(new.created_by, auth.uid());
    return new;
  end if;

  -- Only the status may move after this point; a child never edits the goal.
  if new.family_code is distinct from old.family_code
     or new.kid_id is distinct from old.kid_id
     or new.title is distinct from old.title
     or new.details is distinct from old.details
     or new.bonus_points is distinct from old.bonus_points then
    if caller_role is distinct from 'parent' then
      raise exception 'Only a parent can change a goal' using errcode = '42501';
    end if;
  end if;

  if old.status = 'achieved' then
    if new.status is distinct from 'achieved' then
      raise exception 'An achieved goal keeps its points. Add a new goal instead.';
    end if;
    new.bonus_points := old.bonus_points;
    new.awarded_points := old.awarded_points;
    new.achieved_at := old.achieved_at;
    new.completed_at := old.completed_at;
    new.completed_by := old.completed_by;
    new.kid_id := old.kid_id;
    new.family_code := old.family_code;
    return new;
  end if;

  if caller_role is distinct from 'parent' then
    -- A child marks their own goal done, or takes that back while it waits.
    -- The bonus itself is always a parent's decision.
    if new.kid_id is distinct from auth.uid() then
      raise exception 'That goal is not yours' using errcode = '42501';
    end if;
    if old.status = 'active' and new.status = 'pending' then
      new.completed_at := pg_catalog.now();
      new.completed_by := auth.uid();
    elsif old.status = 'pending' and new.status = 'active' then
      new.completed_at := null;
      new.completed_by := null;
    else
      raise exception 'A parent confirms when a goal is finished' using errcode = '42501';
    end if;
    new.awarded_points := 0;
    new.achieved_at := null;
    return new;
  end if;

  if new.status = 'achieved' then
    new.achieved_at := pg_catalog.now();
    new.awarded_points := new.bonus_points;
    if new.completed_at is null then
      new.completed_at := pg_catalog.now();
      new.completed_by := auth.uid();
    end if;
  else
    new.awarded_points := 0;
    new.achieved_at := null;
    if new.status = 'active' then
      new.completed_at := null;
      new.completed_by := null;
    end if;
  end if;
  return new;
end;
$$;
revoke all on function choretracker_private.prepare_goal_change() from public, anon, authenticated;
drop trigger if exists ct_prepare_goal on public.goals;
create trigger ct_prepare_goal before insert or update on public.goals
  for each row execute function choretracker_private.prepare_goal_change();

-- The bonus is recorded as a point adjustment so it shows up in the child's
-- point history with a reason, exactly like a parent's manual change.
create or replace function choretracker_private.award_goal_points()
returns trigger language plpgsql security definer set search_path = '' as $$
declare caller_name text;
begin
  if new.status = 'achieved' and old.status is distinct from 'achieved'
     and coalesce(new.awarded_points, 0) > 0 then
    select p.full_name into caller_name from public.profiles p where p.id = auth.uid();
    insert into public.point_adjustments (family_code, kid_id, parent_id, parent_name, amount, note, goal_id)
      values (new.family_code, new.kid_id, auth.uid(), coalesce(caller_name, 'A parent'),
              new.awarded_points, 'Goal complete: ' || new.title, new.id);
  end if;
  return new;
end;
$$;
revoke all on function choretracker_private.award_goal_points() from public, anon, authenticated;
drop trigger if exists ct_award_goal_points on public.goals;
create trigger ct_award_goal_points after update on public.goals
  for each row execute function choretracker_private.award_goal_points();

-- The note is mandatory: a child should always be able to read why points
-- moved. The parent identity comes from the session, never the client.
create or replace function choretracker_private.validate_point_adjustment()
returns trigger language plpgsql security definer set search_path = '' as $$
declare caller_name text; caller_family text;
begin
  select p.full_name, p.family_code into caller_name, caller_family
    from public.profiles p
    where p.id = auth.uid() and p.role = 'parent';
  if caller_family is null then
    raise exception 'Only a parent can change a child''s points' using errcode = '42501';
  end if;
  if new.family_code is distinct from caller_family then
    raise exception 'That child is not in your family' using errcode = '42501';
  end if;
  if not exists (select 1 from public.profiles p
      where p.id = new.kid_id and p.family_code = caller_family and p.role = 'kid') then
    raise exception 'That child is not in your family' using errcode = '42501';
  end if;

  new.parent_id := auth.uid();
  new.parent_name := caller_name;
  new.amount := coalesce(new.amount, 0);
  if new.amount = 0 then
    raise exception 'Enter how many points to add or take away';
  end if;
  new.note := pg_catalog.btrim(coalesce(new.note, ''));
  if new.note = '' then
    raise exception 'Add a note so the child knows why';
  end if;
  if new.goal_id is not null and not exists (
      select 1 from public.goals g where g.id = new.goal_id and g.kid_id = new.kid_id) then
    raise exception 'That goal does not belong to this child' using errcode = '42501';
  end if;
  return new;
end;
$$;
revoke all on function choretracker_private.validate_point_adjustment() from public, anon, authenticated;
drop trigger if exists ct_validate_point_adjustment on public.point_adjustments;
create trigger ct_validate_point_adjustment before insert on public.point_adjustments
  for each row execute function choretracker_private.validate_point_adjustment();

-- Prize spending must respect bonuses and deductions too, so a child cannot
-- spend points a parent has taken away.
create or replace function choretracker_private.validate_redemption()
returns trigger language plpgsql security definer set search_path = '' as $$
declare earned bigint; adjusted bigint; spent bigint; caller_name text;
begin
  if auth.uid() is null or new.kid_id is distinct from auth.uid()
    or new.family_code is distinct from (select choretracker_private.current_family())
    or (select choretracker_private.current_role()) is distinct from 'kid' then
    raise exception 'Only a child can redeem their own reward' using errcode = '42501';
  end if;
  perform pg_catalog.pg_advisory_xact_lock(pg_catalog.hashtextextended(auth.uid()::text, 0));
  select p.full_name into caller_name from public.profiles p where p.id = auth.uid();
  if new.kid_name is distinct from caller_name or new.status is distinct from 'pending'
    or new.points_spent is null or new.points_spent < 0 or not exists (
      select 1 from public.rewards r where r.family_code = new.family_code
        and r.title = new.reward_title and r.point_cost = new.points_spent and r.point_cost >= 0
    ) then
    raise exception 'Invalid reward or redemption';
  end if;
  select coalesce(sum(c.points), 0) into earned from public.chores c
    where c.family_code = new.family_code and c.assigned_to_id = auth.uid() and c.status = 'approved';
  select coalesce(sum(a.amount), 0) into adjusted from public.point_adjustments a
    where a.family_code = new.family_code and a.kid_id = auth.uid();
  select coalesce(sum(r.points_spent), 0) into spent from public.redemptions r
    where r.family_code = new.family_code and r.kid_id = auth.uid();
  if new.points_spent > greatest(earned + adjusted - spent, 0) then
    raise exception 'Not enough points';
  end if;
  return new;
end;
$$;
revoke all on function choretracker_private.validate_redemption() from public, anon, authenticated;

-- The stats function gains the adjustment column, so it is replaced instead of
-- altered. Available points now include goal bonuses and deductions.
drop function if exists public.get_family_child_stats();
create function public.get_family_child_stats()
returns table (child_id uuid, child_name text, completed_chores bigint, points_earned bigint,
               points_adjusted bigint, points_spent bigint, points_available bigint)
language plpgsql stable security definer set search_path = '' as $$
declare caller_family text; caller_role text;
begin
  select p.family_code, p.role into caller_family, caller_role from public.profiles p where p.id = auth.uid();
  if caller_family is null or caller_family = '' or caller_role is null or caller_role not in ('parent', 'kid') then
    raise exception 'A family profile is required' using errcode = '42501';
  end if;
  return query select child.id, child.full_name::text,
    coalesce(c.completed, 0)::bigint, coalesce(c.earned, 0)::bigint,
    case when caller_role = 'parent' then coalesce(a.adjusted, 0)::bigint else 0::bigint end,
    case when caller_role = 'parent' then coalesce(r.spent, 0)::bigint else null::bigint end,
    case when caller_role = 'parent'
      then greatest(coalesce(c.earned, 0) + coalesce(a.adjusted, 0) - coalesce(r.spent, 0), 0)::bigint
      else null::bigint end
  from public.profiles child
  left join lateral (select count(*) as completed, coalesce(sum(ch.points), 0) as earned from public.chores ch
    where ch.family_code = caller_family and ch.assigned_to_id = child.id and ch.status = 'approved') c on true
  left join lateral (select coalesce(sum(adj.amount), 0) as adjusted from public.point_adjustments adj
    where adj.family_code = caller_family and adj.kid_id = child.id) a on true
  left join lateral (select coalesce(sum(rd.points_spent), 0) as spent from public.redemptions rd
    where rd.family_code = caller_family and rd.kid_id = child.id) r on true
  where child.family_code = caller_family and child.role = 'kid';
end;
$$;
revoke all on function public.get_family_child_stats() from public, anon;
grant execute on function public.get_family_child_stats() to authenticated;

commit;
