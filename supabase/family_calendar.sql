-- Family calendar. Apply after family_invitations.sql and family_access.sql.
-- Parents create, edit, and approve events; children can only suggest them.
-- Visibility 'parents' hides an event from children entirely.
-- Recurrence is stored as a simple rule and expanded by the app.
-- Back up and test in staging before applying to a live project.
begin;

do $$
begin
  if (select count(*) from pg_catalog.pg_class c join pg_catalog.pg_namespace n on n.oid = c.relnamespace
      where n.nspname = 'public' and c.relname in ('profiles', 'chores', 'chore_templates', 'rewards', 'redemptions') and c.relrowsecurity) <> 5
     or not exists (select 1 from pg_catalog.pg_policies where schemaname = 'public' and tablename = 'profiles' and policyname = 'ct_profiles_read')
     or pg_catalog.to_regprocedure('choretracker_private.current_family()') is null
     or pg_catalog.to_regprocedure('choretracker_private.current_role()') is null
     or not exists (select 1 from pg_catalog.pg_trigger where tgrelid = 'public.profiles'::regclass
       and tgname = 'choretracker_guard_profiles' and tgenabled in ('O', 'A')) then
    raise exception 'Install and verify family_invitations.sql and family_access.sql before adding the calendar.';
  end if;
end;
$$;

create table if not exists public.calendar_events (
  id bigint generated by default as identity primary key,
  family_code text not null,
  title text not null check (pg_catalog.char_length(pg_catalog.btrim(title)) between 1 and 120),
  notes text,
  starts_at timestamptz not null,
  ends_at timestamptz,
  all_day boolean not null default false,
  visibility text not null default 'family' check (visibility in ('family', 'parents')),
  status text not null default 'approved' check (status in ('approved', 'suggested', 'declined')),
  recurrence text not null default 'none' check (recurrence in ('none', 'daily', 'weekly', 'monthly')),
  recurrence_interval integer not null default 1 check (recurrence_interval between 1 and 12),
  recurrence_until date,
  created_by uuid references auth.users (id) on delete set null,
  suggested_by uuid references auth.users (id) on delete set null,
  created_at timestamptz not null default now(),
  constraint calendar_events_time_order check (ends_at is null or ends_at >= starts_at),
  constraint calendar_events_until_requires_repeat check (recurrence <> 'none' or recurrence_until is null),
  constraint calendar_events_suggestion_has_author check (status <> 'suggested' or suggested_by is not null)
);

create index if not exists calendar_events_family_start_idx on public.calendar_events (family_code, starts_at);
create index if not exists calendar_events_pending_idx on public.calendar_events (family_code) where status = 'suggested';

alter table public.calendar_events enable row level security;
revoke all on public.calendar_events from public, anon;
grant select, insert, update, delete on public.calendar_events to authenticated;
grant usage, select on all sequences in schema public to authenticated;

-- Force authorship and the child suggestion state on the server; a client
-- cannot insert an already-approved event or attribute it to someone else.
create or replace function choretracker_private.prepare_calendar_event()
returns trigger language plpgsql security invoker set search_path = '' as $$
declare caller_role text;
begin
  if auth.uid() is null then
    return new;
  end if;
  select choretracker_private.current_role() into caller_role;
  if tg_op = 'INSERT' then
    new.created_by := auth.uid();
    if caller_role = 'kid' then
      new.status := 'suggested';
      new.visibility := 'family';
      new.suggested_by := auth.uid();
    else
      new.status := 'approved';
      new.suggested_by := null;
    end if;
  elsif caller_role = 'kid' then
    raise exception 'Only a parent can change a calendar event' using errcode = '42501';
  end if;
  return new;
end;
$$;
revoke all on function choretracker_private.prepare_calendar_event() from public, anon, authenticated;
drop trigger if exists ct_prepare_calendar_event on public.calendar_events;
create trigger ct_prepare_calendar_event before insert or update on public.calendar_events
  for each row execute function choretracker_private.prepare_calendar_event();

drop policy if exists ct_calendar_read on public.calendar_events;
create policy ct_calendar_read on public.calendar_events for select to authenticated using (
  family_code = (select choretracker_private.current_family()) and (
    (select choretracker_private.current_role()) = 'parent'
    or (visibility = 'family' and status = 'approved')
    or suggested_by = (select auth.uid())
  )
);

drop policy if exists ct_calendar_insert on public.calendar_events;
create policy ct_calendar_insert on public.calendar_events for insert to authenticated with check (
  family_code = (select choretracker_private.current_family()) and (
    ((select choretracker_private.current_role()) = 'parent' and status = 'approved' and created_by = (select auth.uid()))
    or ((select choretracker_private.current_role()) = 'kid' and status = 'suggested' and visibility = 'family'
        and suggested_by = (select auth.uid()) and created_by = (select auth.uid()))
  )
);

drop policy if exists ct_calendar_update on public.calendar_events;
create policy ct_calendar_update on public.calendar_events for update to authenticated using (
  family_code = (select choretracker_private.current_family()) and (select choretracker_private.current_role()) = 'parent'
) with check (
  family_code = (select choretracker_private.current_family()) and (select choretracker_private.current_role()) = 'parent'
);

drop policy if exists ct_calendar_delete on public.calendar_events;
create policy ct_calendar_delete on public.calendar_events for delete to authenticated using (
  family_code = (select choretracker_private.current_family()) and (
    (select choretracker_private.current_role()) = 'parent'
    or (status = 'suggested' and suggested_by = (select auth.uid()))
  )
);

commit;
